#!/usr/bin/env python3
"""AEGIS - Second-assay cross-check: REFERENCE IMPLEMENTATION (Python 3 stdlib only).

OSD-575 measured the same serum samples on two independent platforms:
  primary  = Eve Technologies bead multiplex (pg/mL)   -> file name contains 'serum_immune'
  second   = Alamar NULISAseq (NPQ, log2 units)        -> file name contains 'Alamar'
Usage: python3 reference_second_assay.py <data_dir> > expected_second_assay.json
"""
import csv, json, math, os, re, statistics as st, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import reference_engine as R

CONFIRM_LOG2 = 0.5        # A: a change counts when it is at least 0.5 log2 units (about +41 % / -29 %)
PAIRS = {'il_6': 'il6', 'il_8': 'cxcl8', 'mcp_1': 'ccl2', 'il_10': 'il10', 'il_27': 'il27'}
MAP_ALL = {'il_6':'il6','mcp_1':'ccl2','il_10':'il10','il_27':'il27','tnfα':'tnf','ip_10':'cxcl10','il_8':'cxcl8','il_1ra':'il1rn','il_1β':'il1b',
           'il_18':'il18','il_4':'il4','il_5':'il5','il_7':'il7','il_13':'il13','il_17a':'il17a','ifnγ':'ifng','mcp_2':'ccl8','mcp_3':'ccl7',
           'mcp_4':'ccl13','mip_1α':'ccl3','mip_1β':'ccl4','rantes':'ccl5','tarc':'ccl17','mdc':'ccl22','i_309':'ccl1','groα':'cxcl1','ena_78':'cxcl5',
           'fractalkine':'cx3cl1','g_csf':'csf3','m_csf':'csf1','vegf_a':'vegfa','egf':'egf','fgf_2':'fgf2','flt_3l':'flt3lg','il_12p70':'il12p70',
           'il_12p40':'il12b','il_33':'il33','il_22':'il22','il_23':'il23','il_9':'il9','lif':'lif','tslp':'tslp','tpo':'thpo','trail':'tnfsf10',
           'scf':'kitlg','sdf_1α_plus_β':'cxcl12','mig_per_cxcl9':'cxcl9','bca_1':'cxcl13','eotaxin_2':'ccl24','mip_1δ':'ccl15','il_16':'il16',
           'il_20':'il20','il_17f':'il17f','ifn_α2':'ifna2','pdgf_aa':'pdgfa'}

def read_alamar(path):
    with open(path, encoding='utf-8-sig', newline='') as fh:
        rows = list(csv.reader(fh))
    header, body = rows[0], rows[1:]
    cols = {m.group(1): i for i, c in enumerate(header) if (m := re.match(r'(.+)_concentration_npq$', c))}
    out = {a: {c: {} for c in R.CREW} for a in cols}
    for r in body:
        p = r[0].split('_')                     # C001_serum_L-92
        for a, i in cols.items():
            try:
                out[a][p[0]][p[2]] = float(r[i])
            except (ValueError, IndexError):
                pass
    return out

def dev_primary(E, m, c, t):
    ser = E[m][c]; p = [ser[x] for x in R.PRE if x in ser]
    if t not in ser or len(p) < 2: return None
    return math.log2(ser[t] / st.median(p))

def dev_second(A, a, c, t):
    ser = A[a][c]; p = [ser[x] for x in R.PRE if x in ser]
    if t not in ser or len(p) < 2: return None
    return ser[t] - st.median(p)                # NPQ is already log2

def status(d1, d2):
    if d1 is None or d2 is None: return 'NO_SECOND_ASSAY'
    if abs(d1) < CONFIRM_LOG2: return 'NOT_APPLICABLE'
    return 'CONFIRMED' if (d1 > 0) == (d2 > 0) and abs(d2) >= CONFIRM_LOG2 else 'NOT_CONFIRMED'

def spearman(x, y):
    def rk(v):
        o = sorted(range(len(v)), key=lambda i: v[i]); r = [0.0] * len(v)
        for pos, i in enumerate(o): r[i] = pos
        return r
    rx, ry = rk(x), rk(y); mx = (len(x) - 1) / 2
    den = sum((a - mx) ** 2 for a in rx)
    return sum((a - mx) * (b - mx) for a, b in zip(rx, ry)) / den if den else None

def main(data_dir):
    E = R.read_table(R.find_file(data_dir, 'serum_immune'), 'immune')
    A = read_alamar(R.find_file(data_dir, 'Alamar'))
    base = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'expected_values.json'), encoding='utf-8'))
    out = {'_readme': 'Generated by reference_second_assay.py. Do not edit by hand.', 'CONFIRM_LOG2': CONFIRM_LOG2,
           'second_assay_analytes': len(A), 'missing_second_assay_samples': [f'{c}_{t}' for c in R.CREW for t in R.TPS if t not in A['il6'][c]]}
    panels = {}
    for c in R.CREW:
        for t in R.POST:
            row = {}
            for m in ('il_6', 'il_8'):
                d1, d2 = dev_primary(E, m, c, t), dev_second(A, PAIRS[m], c, t)
                row[m] = {'primary_log2': round(d1, 2), 'second_log2': round(d2, 2), 'primary_fold': round(2 ** d1, 2),
                          'second_fold': round(2 ** d2, 2), 'status': status(d1, d2)}
            cls = base['panels'][f'{c}_{t}']['class']
            row['class'] = cls
            row['badge'] = None if cls not in ('EXPECTED_FLIGHT_RESPONSE', 'UNEXPECTED_ACTIVATION') else \
                ('TWO_ASSAY_CONFIRMED' if row['il_6']['status'] == 'CONFIRMED' else 'SINGLE_ASSAY')
            panels[f'{c}_{t}'] = row
    out['panels'] = panels
    out['signature_cytokines_R1'] = {m: {'primary_log2': [round(dev_primary(E, m, c, 'R+1'), 2) for c in R.CREW],
                                         'second_log2': [round(dev_second(A, PAIRS[m], c, 'R+1'), 2) for c in R.CREW]} for m in ('il_6', 'mcp_1', 'il_10', 'il_27')}
    rho = {}
    for m, a in MAP_ALL.items():
        if m not in E or a not in A: continue
        rs = []
        for c in R.CREW:
            tps = [t for t in R.TPS if t in E[m][c] and t in A[a][c]]
            ys = [A[a][c][t] for t in tps]
            if len(tps) >= 5 and len(set(ys)) > 2: rs.append(spearman([E[m][c][t] for t in tps], ys))
        if rs: rho[m] = round(sum(rs) / len(rs), 2)
    vals = sorted(rho.values())
    out['agreement'] = {'matched_pairs': len(rho), 'median_within_person_rho': round(st.median(vals), 2),
                        'pairs_with_rho_ge_0.5': sum(v >= 0.5 for v in vals), 'rho': {m: rho[m] for m in ('il_6', 'il_8', 'mcp_1', 'il_10', 'il_27')}}
    both = []
    for m, a in MAP_ALL.items():
        if m not in E or a not in A: continue
        d1 = [dev_primary(E, m, c, 'R+1') for c in R.CREW]; d2 = [dev_second(A, a, c, 'R+1') for c in R.CREW]
        if (all(x > 0 for x in d1) and all(x > 0 for x in d2)) or (all(x < 0 for x in d1) and all(x < 0 for x in d2)): both.append(m)
    out['same_direction_4of4_on_both_assays_at_R1'] = both
    n = low = 0
    for a in A:
        for c in R.CREW:
            v = [A[a][c].get(t) for t in R.PRE]
            if None in v or len(set(v)) < 3: continue
            n += 1; low += v[1] == min(v)
    out['L44_lowest_on_second_assay'] = {'n': n, 'lowest': low, 'share': round(low / n, 2)}
    xs, ys = [], []
    for c in R.CREW:
        for t in R.POST:
            xs.append(dev_primary(E, 'il_6', c, t)); ys.append(dev_second(A, 'il6', c, t))
    out['il6_16_panels'] = {'spearman': round(spearman(xs, ys), 2), 'same_sign': sum((x > 0) == (y > 0) for x, y in zip(xs, ys))}
    return out

if __name__ == '__main__':
    json.dump(main(sys.argv[1] if len(sys.argv) > 1 else 'data'), sys.stdout, indent=1, ensure_ascii=False)
