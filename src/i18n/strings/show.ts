/** the "checkin.*" or "dashboard.*" half of showStrings, for the area it is merged into */
export function showArea(prefix: "checkin." | "dashboard."): AreaDicts {
  const pick = (d: Record<string, string>) => Object.fromEntries(Object.entries(d).filter(([k]) => k.startsWith(prefix)));
  return { en: pick(showStrings.en), mn: pick(showStrings.mn) };
}
